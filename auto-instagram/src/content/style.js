export const DEFAULT_STYLE = 'casual-diary';

/**
 * data/style-samples.json を読む。
 * 形式: { "profile": "casual-diary", "samples": ["投稿本文", ...] }
 */
/** 文体の材料にならない短すぎるものを落とし、上限で切る */
function tidySamples(list) {
  return list
    .map((s) => String(s ?? '').trim())
    .filter((s) => s.length >= 10)
    .slice(0, 20);   // 多すぎてもトークンを食うだけ
}

/**
 * 同じ場所にある .txt から追加のサンプルを読む。
 *
 * JSON は引用符と改行のエスケープが要るので、スマホから投稿を貼るのが苦痛になる。
 * 実投稿をそのまま貼れるように、--- の行で区切るだけのプレーンテキストも受ける。
 * # で始まる行はコメントとして無視する。
 */
function loadTextSamples(jsonFile) {
  const txt = jsonFile.replace(/\.json$/, '.txt');
  try {
    if (!fs.existsSync(txt)) return [];
    return fs.readFileSync(txt, 'utf8')
      .split(/^\s*-{3,}\s*$/m)
      .map((block) => block.split('\n').filter((l) => !l.startsWith('#')).join('\n').trim())
      .filter(Boolean);
  } catch (e) {
    warn(`文体サンプル(.txt)の読み込みに失敗: ${e.message}`);
    return [];
  }
}

export function loadStyleSamples(file) {
  let profile = null;
  let fromJson = [];
  try {
    if (fs.existsSync(file)) {
      const raw = JSON.parse(fs.readFileSync(file, 'utf8'));
      profile = raw.profile ?? null;
      fromJson = raw.samples ?? [];
    }
  } catch (e) {
    warn(`文体サンプルの読み込みに失敗: ${e.message}`);
  }
  // .txt を先に置く。手で貼った実投稿のほうが、こちらが用意した例より信頼できる
  return { profile, samples: tidySamples([...loadTextSamples(file), ...fromJson]) };
}

/** 実サンプルからURL・ハッシュタグ・メンションを落とす（文体だけを見せたい） */
export function stripNoise(text) {
  return String(text)
    .replace(/https?:\/\/\S+/g, '')
    .replace(/[#＃][^\s#＃]+/g, '')
    .replace(/@\w+/g, '')
    .replace(/[ \t]{2,}/g, ' ')
    .trim();
}

export function resolveStyle(name) {
  return STYLE_PRESETS[name] ?? STYLE_PRESETS[DEFAULT_STYLE];
}

/**
 * プロンプトに差し込む文体セクションを組み立てる。
 * サンプルがあれば few-shot として最優先で見せ、無ければプリセットの記述だけを使う。
 */
export function buildStyleSection({ styleName, samples = [], owned }) {
  const style = resolveStyle(styleName);
  const verbs = owned ? style.ownedVerbs : style.unownedVerbs;

  const parts = [style.rules];

  if (samples.length) {
    const list = samples
      .map(stripNoise)
      .filter(Boolean)
      .map((s, i) => `${i + 1}) ${s}`)
      .join('\n');
    parts.push(`【お手本（実際の投稿。この語り口・リズム・粒度を真似る）】
${list}

上のサンプルから真似るのは **語り口・文の始め方・ディテールの粒度・感情の出し方** です。
サンプルに出てくる商品・エピソード・固有名詞そのものは絶対に流用しないこと。`);
  }

  parts.push(`【この商品での言い回し】
${owned
    ? `実際に持っている商品なので、${verbs} のような所有・使用を前提にした言い方をしてよい。`
    : `まだ持っていない商品なので、${verbs} のような検討中の言い方にする。\n「ぽちった」「使ってる」「届いた」は書かない（持っていないため）。`}`);

  return parts.join('\n\n');
}
