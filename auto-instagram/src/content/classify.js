/**
 * 投稿テキストから「書き出しの型」を判定する。
 *
 * ■ なぜ保存した angle を使わないのか
 * 生成時に angle を queue.json に持たせてはいるが、実績の集計には使えない。
 *   - 実際に投稿するのは3パターンから選んだ1本で、どれを選んだかは機械に分からない
 *   - 手で直して投稿することが普通にある（むしろ推奨される）
 *   - queue.json は30日で掃除されるし、この仕組みより前の投稿には何も残っていない
 * 投稿された文そのものから型を読み取れば、どの経路で出した投稿でも同じ尺度で測れる。
 *
 * ■ 精度について
 * これは正規表現によるおおまかな分類で、外れることがある。
 * 型の優劣を比べるための「束ね方」なので、1本1本の正解は必要なく、
 * 束ごとの傾向が見えれば足りる。判定できないものは other に落とし、
 * other が多すぎるときは分類を見直す合図として件数を出す。
 */

/** 型の定義。label は digest にそのまま出る */
export const OPENING_TYPES = {
  'image-update': { label: 'イメージの更新' },
  emotion: { label: '感情を先に出す' },
  price: { label: '値段から入る' },
  event: { label: '日付・セールから入る' },
  spec: { label: 'スペックへの引っかかり' },
  other: { label: 'その他' },
};

export const DEFAULT_TYPE = 'other';

/** 判定は上から順に当てる。先に書いたものが優先される */
const RULES = [
  // 「え、〇〇って△△しか知らなかったけど、〜あったのか…。」
  ['image-update', /^え[、,]|と思って(た|いた)けど|しか知らなかった|あったのか|知らなかった/],
  // 「これー！！！買った！！！！」「まじでまじでまじで」
  ['emotion', /[！!]{2,}|^まじで|^やば|^うれし|^嬉し/],
  // 「買ったのこれ⬇︎1680円。」「1680円。」
  ['price', /^[\d０-９,，]+円|^買ったのこれ|^[^。]{0,12}[\d０-９,，]+円/],
  // 「11/10に0と5のつく日くるんだった」
  ['event', /^[^。]{0,12}([\d０-９]{1,2}\s*[\/／月]\s*[\d０-９]{1,2}|お買い物マラソン|スーパーSALE|0と5のつく日|ワンダフルデー)/],
  // 「内側セラミックコーティングって見て手が止まった」「初めて見た」
  ['spec', /手が止まった|初めて見た|って(見て|書いてあって|見た時)|って表記|なんだ、って/],
];

/**
 * 1本の投稿本文から型を返す。
 * 先頭の空行・記号は判定の邪魔になるので落としてから見る。
 */
export function classifyOpening(text) {
  const s = String(text ?? '')
    .replace(/^[\s　]+/, '')
    .replace(/^[【\[][^】\]]{0,20}[】\]]\s*/, '')   // 冒頭の【PR】などは型ではない
    .trim();
  if (!s) return DEFAULT_TYPE;
  for (const [type, re] of RULES) if (re.test(s)) return type;
  return DEFAULT_TYPE;
}

/** digest 表示用のラベル。未知の型でも落ちないようにしておく */
export function typeLabel(type) {
  return OPENING_TYPES[type]?.label ?? type;
}
